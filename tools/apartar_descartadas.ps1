if ((Read-Host 'Escribí S y Enter para seguir') -notin 's','S') { Write-Host 'Cancelado.'; exit }
foreach ($f in $archivos) {
  $rel = $f.DirectoryName.Substring($raiz.Length).TrimStart([char]92)
  $dir = Join-Path $destino $rel
  New-Item -ItemType Directory -Force -Path $dir | Out-Null
  Move-Item -LiteralPath $f.FullName -Destination (Join-Path $dir $f.Name)
}
