function Norm($t) { return $t.Normalize([Text.NormalizationForm]::FormC).Trim().ToLowerInvariant() }
$setQ = @{}; foreach ($t in $quitadas) { $setQ[(Norm $t)] = $true }
$setK = @{}; foreach ($t in $quedan) { $setK[(Norm $t)] = $true }
$ext = '.jpg','.jpeg','.png','.webp'
$archivos = Get-ChildItem -LiteralPath $raiz -Recurse -File | Where-Object {
  ($ext -contains $_.Extension.ToLower()) -and $setQ.ContainsKey((Norm $_.BaseName)) -and -not $setK.ContainsKey((Norm $_.BaseName))
}
if (-not $archivos) { Write-Host 'No hay nada para apartar.'; Read-Host 'Enter para salir'; exit }
$archivos | ForEach-Object { Write-Host ($_.FullName.Substring($raiz.Length + 1)) }
